def quiz_order(questions=QUESTIONS):
    """Indexes into `questions` in the fixed order every team receives.

    Cycles easy -> medium -> tough. Inside each difficulty the questions are taken
    round-robin across themes so consecutive questions rarely share a theme.
    """
    theme_rank = {t: n for n, t in enumerate(THEMES)}
    by_level = {level: [] for level in DIFFICULTIES}
    for idx, q in enumerate(questions):
        by_level[q[1]].append(idx)
    for shift, (level, idxs) in enumerate(by_level.items()):
        seen = {}
        keyed = []
        for idx in idxs:
            theme = questions[idx][0]
            seen[theme] = seen.get(theme, 0) + 1
            # each difficulty starts at a different theme so an easy/medium/tough
            # triple does not come from one theme
            keyed.append((seen[theme], (theme_rank[theme] - 3 * shift) % len(THEMES), idx))
        by_level[level] = [idx for _, _, idx in sorted(keyed)]
    order = []
    pools = [list(by_level[level]) for level in DIFFICULTIES]
    while any(pools):
        for pool in pools:
            if pool:
                order.append(pool.pop(0))
    return order


